// MARK: - Clipboard history

/// Remembers recent text you copied (in memory only; never saved to disk).
final class ClipboardMonitor: PollingMonitor {
    static let shared = ClipboardMonitor()

    struct Clip: Identifiable, Equatable {
        let id = UUID()
        let text: String
        let date: Date
    }

    @Published private(set) var clips: [Clip] = []
    @Published var isPaused = false

    private var lastChange = NSPasteboard.general.changeCount
    override var interval: TimeInterval { 1 }

    /// Password managers mark secrets with these types; never record them.
    private static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    override func sample() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        guard !isPaused else { return }
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.concealedTypes),
              let text = board.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
              !text.isEmpty else { return }
        var list = clips.filter { $0.text != text }
        list.insert(Clip(text: String(text.prefix(2000)), date: Date()), at: 0)
        clips = Array(list.prefix(25))
    }

    func copy(_ clip: Clip) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(clip.text, forType: .string)
        lastChange = NSPasteboard.general.changeCount
        clips = [clip] + clips.filter { $0.id != clip.id }
    }

    func clear() {
        clips = []
    }
}

// MARK: - Volume

final class VolumeMonitor: PollingMonitor {
    static let shared = VolumeMonitor()

    @Published private(set) var volume: Double = 0.5
    @Published private(set) var isMuted = false
    private let queue = DispatchQueue(label: "HomeWidgets.volume", qos: .userInitiated)
    private var lastSet = Date.distantPast

    override var interval: TimeInterval { 2 }

    override func sample() {
        // Don't fight the slider while the user is dragging it.
        guard Date().timeIntervalSince(lastSet) > 1.5 else { return }
        queue.async { [weak self] in
            let (result, _) = Shell.runAppleScriptNow("set s to (get volume settings)\nreturn {output volume of s, output muted of s}")
            guard let result, result.numberOfItems >= 2 else { return }
            let level = Double(result.atIndex(1)?.int32Value ?? 50) / 100
            let muted = result.atIndex(2)?.booleanValue ?? false
            DispatchQueue.main.async {
                guard let self else { return }
                if abs(self.volume - level) > 0.005 { self.volume = level }
                if self.isMuted != muted { self.isMuted = muted }
            }
        }
    }

    func set(_ level: Double) {
        volume = min(1, max(0, level))
        lastSet = Date()
        let percent = Int((volume * 100).rounded())
        queue.async {
            _ = Shell.runAppleScriptNow("set volume output volume \(percent) without output muted")
        }
        if isMuted { isMuted = false }
    }

    func toggleMute() {
        isMuted.toggle()
        lastSet = Date()
        let muted = isMuted
        queue.async {
            _ = Shell.runAppleScriptNow("set volume output muted \(muted)")
        }
    }
}

// MARK: - Wi-Fi

final class WiFiMonitor: PollingMonitor {
    static let shared = WiFiMonitor()

    @Published private(set) var isOn = false
    @Published private(set) var networkName: String?
    @Published private(set) var rssi = 0
    @Published private(set) var noise = 0
    @Published private(set) var transmitRate: Double = 0
    @Published private(set) var channel: Int?
    @Published private(set) var band: String?
    @Published private(set) var history = MetricHistory()

    override var interval: TimeInterval { 3 }

    /// 0...4 bars, like the menu bar icon.
    var bars: Int {
        guard isOn, rssi != 0 else { return 0 }
        switch rssi {
        case (-55)...: return 4
        case (-65)...: return 3
        case (-75)...: return 2
        default: return 1
        }
    }

    var quality: String {
        switch bars {
        case 4: return "Excellent"
        case 3: return "Good"
        case 2: return "Fair"
        case 1: return "Weak"
        default: return "Not connected"
        }
    }

    override func sample() {
        guard let interface = CWWiFiClient.shared().interface() else {
            isOn = false
            return
        }
        isOn = interface.powerOn()
        rssi = interface.rssiValue()
        noise = interface.noiseMeasurement()
        transmitRate = interface.transmitRate()
        networkName = interface.ssid()
        if let wlan = interface.wlanChannel() {
            channel = wlan.channelNumber
            switch wlan.channelBand {
            case .band2GHz: band = "2.4 GHz"
            case .band5GHz: band = "5 GHz"
            case .band6GHz: band = "6 GHz"
            default: band = nil
            }
        } else {
            channel = nil
            band = nil
        }
        // Map -90…-30 dBm to 0…1 for the graph.
        history.append(rssi == 0 ? 0 : min(1, max(0, Double(rssi + 90) / 60)))
    }
}

// MARK: - Disk activity

final class DiskActivityMonitor: PollingMonitor {
    static let shared = DiskActivityMonitor()

    /// Bytes per second.
    @Published private(set) var readRate: Double = 0
    @Published private(set) var writeRate: Double = 0
    @Published private(set) var readHistory = MetricHistory()
    @Published private(set) var writeHistory = MetricHistory()

    private var last: (read: UInt64, write: UInt64, time: Date)?

    override func sample() {
        var iterator: io_iterator_t = 0
        guard IOServiceGetMatchingServices(kIOMainPortDefault, IOServiceMatching("IOBlockStorageDriver"), &iterator) == KERN_SUCCESS else { return }
        defer { IOObjectRelease(iterator) }
        var totalRead: UInt64 = 0
        var totalWrite: UInt64 = 0
        var service = IOIteratorNext(iterator)
        while service != 0 {
            if let stats = IORegistryEntryCreateCFProperty(service, "Statistics" as CFString, kCFAllocatorDefault, 0)?
                .takeRetainedValue() as? [String: Any] {
                totalRead += (stats["Bytes (Read)"] as? NSNumber)?.uint64Value ?? 0
                totalWrite += (stats["Bytes (Write)"] as? NSNumber)?.uint64Value ?? 0
            }
            IOObjectRelease(service)
            service = IOIteratorNext(iterator)
        }
        let now = Date()
        if let last, totalRead >= last.read, totalWrite >= last.write {
            let elapsed = max(0.1, now.timeIntervalSince(last.time))
            readRate = Double(totalRead - last.read) / elapsed
            writeRate = Double(totalWrite - last.write) / elapsed
            readHistory.append(readRate)
            writeHistory.append(writeRate)
        }
        last = (totalRead, totalWrite, now)
    }

    override func didStop() {
        last = nil
    }
}
